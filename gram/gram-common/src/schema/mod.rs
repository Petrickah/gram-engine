//! Component schemas (`.ron` files starting with `Component(`) and the two files generated from
//! them for each cargo module: `components.generated.rs` and `Components.generated.hpp`.
//!
//! `generate` (the schema model, the layout and the emitted code) is the user's to write; the
//! rest of this module (`find`, `write_if_changed`) is the plumbing that feeds and stores it.

use std::fmt::Write;
use std::io;
use std::path::Path;
use std::path::PathBuf;

mod files;
pub(crate) use files::{find, write_if_changed};
use serde::Deserialize;

/// The generated Rust module, next to the module's `Cargo.toml` (included with `#[path]`).
pub const RUST_FILE: &str = "components.generated.rs";
/// The generated C++ header, next to it (header-only: the descriptors are `inline`).
pub const CPP_FILE: &str = "Components.generated.hpp";

/// One schema file of a module: where it is (relative to the module's directory, for messages)
/// and its text, not parsed yet.
pub struct SchemaFile {
    pub path: PathBuf,
    pub source: String,
}

/// The content of the two generated files.
pub struct Generated {
    pub rust: String,
    pub cpp: String,
}

/// The schema type for a component; it's a name with a collection of Field structs.
#[derive(Debug, Deserialize)]
struct Component {
    name: String,
    fields: Vec<Field>
}

#[derive(Debug, Deserialize)]
struct Field {
    name: String,
    ty: FieldType
}

#[derive(Debug, Deserialize)]
enum FieldType {
    Str(usize), F32, I32, U32, Bool
}

impl FieldType {
    pub fn kind(&self) -> &'static str {
        match self {
            FieldType::Str(_) => "Str",
            FieldType::F32 => "F32",
            FieldType::I32 => "I32",
            FieldType::U32 => "U32",
            FieldType::Bool => "Bool",
        }
    }

    pub fn size_align(&self) -> (usize, usize) {
        match self {
            FieldType::Str(n) => (*n, 1),
            FieldType::F32 => (4, 4),
            FieldType::I32 => (4, 4),
            FieldType::U32 => (4, 4),
            FieldType::Bool => (1, 1),
        }
    }

    pub fn rust(&self, name: &str) -> String {
        match self {
            FieldType::Str(n) => format!("{}: Str<{}>", name, n),
            FieldType::F32 => format!("{}: f32", name),
            FieldType::I32 => format!("{}: i32", name),
            FieldType::U32 => format!("{}: u32", name),
            FieldType::Bool => format!("{}: bool", name),
        }
    }

    pub fn cpp(&self, name: &str) -> String {
        match self {
            FieldType::Str(n) => format!("char {}[{}]", name, n),
            FieldType::F32 => format!("float {}", name),
            FieldType::I32 => format!("int32_t {}", name),
            FieldType::U32 => format!("uint32_t {}", name),
            FieldType::Bool => format!("bool {}", name),
        }
    }
}

impl Component {
    pub fn read(file: &Path, source: &str) -> io::Result<Self> {
        ron::de::from_str(source)
            .map_err(|err| io::Error::new(io::ErrorKind::InvalidData, format!("{}: {err}", file.display())))
    }

    pub fn layout(&self) -> (Vec<usize>, usize) {
        let mut offsets: Vec<usize> = Vec::new();
        let mut offset = 0;
        let mut max_align = 1;   // 1, not 0: a component without fields has size 0
        for field in &self.fields {
            let (size, align) = field.ty.size_align();
            offset = (offset + align - 1) / align * align;
            offsets.push(offset);
            offset += size;
            max_align = max_align.max(align);
        }
        let size = (offset + max_align - 1) / max_align * max_align;
        (offsets, size)
    }
}

/// Turns every schema of one module into the two generated files. An error (a schema that doesn't
/// parse, an unknown field type) should name the schema's `path`.
pub fn generate(schemas: &[SchemaFile]) -> io::Result<Generated> {
    let components = schemas.iter()
        .map(|schema| Component::read(&schema.path, &schema.source))
        .collect::<io::Result<Vec<_>>>()?;

    Ok(Generated { rust: emit_rust(&components), cpp: emit_cpp(&components) })
}

fn emit_rust(components: &[Component]) -> String {
    let mut out = String::new();
    writeln!(out, "// Generated by gram from the .ron schemas in Content/. Don't edit.").unwrap();
    // gram_core's own list for generated code, not the game's prelude: the generated code mustn't
    // depend on what a game chose to import (and that prelude re-exports these components).
    writeln!(out, "use gram_core::codegen::*;").unwrap();

    for c in components {
        let (offsets, size) = c.layout();
        writeln!(out).unwrap();
        writeln!(out, "#[repr(C)]").unwrap();
        writeln!(out, "#[derive(Debug)]").unwrap();
        writeln!(out, "pub struct {} {{", c.name).unwrap();
        for field in &c.fields {
            writeln!(out, "    pub {},", field.ty.rust(&field.name)).unwrap();
        }
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "impl Component for {} {{", c.name).unwrap();
        writeln!(out, "    const ID: ComponentID = component_id(\"{}\");", c.name).unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "const _: () = assert!(std::mem::size_of::<{}>() == {});", c.name, size).unwrap();
        for (field, offset) in c.fields.iter().zip(&offsets) {
            writeln!(out, "const _: () = assert!(std::mem::offset_of!({}, {}) == {});", c.name, field.name, offset).unwrap();
        }
    }
    out
}

fn capitalize_first(word: &str) -> String {
    let mut chars = word.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn pascal_case(name: &str) -> String {
    name.split("_").map(capitalize_first).collect::<String>()
}

fn emit_cpp(components: &[Component]) -> String {
    let mut out = String::new();
    writeln!(out, "// Generated by gram from the .ron schemas in Content/. Don't edit.").unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "GRAM_NAMESPACE_BEGIN").unwrap();

    for c in components {
        let (offsets, size) = c.layout();
        writeln!(out).unwrap();
        writeln!(out, "struct {} {{", c.name).unwrap();
        for field in &c.fields {
            let name = pascal_case(&field.name);
            writeln!(out, "    {};", field.ty.cpp(&name)).unwrap();
        }
        writeln!(out, "}};").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "static_assert(sizeof({}) == {});", c.name, size).unwrap();
        for (field, offset) in c.fields.iter().zip(&offsets) {
            let name = pascal_case(&field.name);
            writeln!(out, "static_assert(offsetof({}, {}) == {});", c.name, name, offset).unwrap();
        }
        writeln!(out).unwrap();
        writeln!(out, "inline const Gram::FieldDescriptor {}Fields[] =", c.name).unwrap();
        writeln!(out, "{{").unwrap();
        for field in &c.fields  {
            let name = pascal_case(&field.name);
            writeln!(out, "    {{ \"{}\", Gram::FieldDescriptor::FieldType::{}, offsetof({}, {}), sizeof({}::{}) }},", name, field.ty.kind(), c.name, name, c.name, name).unwrap();
        }
        writeln!(out, "}};").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "inline const ComponentDescriptor {}Descriptor =", c.name).unwrap();
        writeln!(out, "{{").unwrap();
        writeln!(out, "    .Name   = \"{}\",", c.name).unwrap();
        writeln!(out, "    .ID     = ComponentIDFromName(\"{}\"),", c.name).unwrap();
        writeln!(out, "    .Fields = {}Fields,", c.name).unwrap();
        writeln!(out, "    .Count  = std::size({}Fields),", c.name).unwrap();
        writeln!(out, "    .Size   = sizeof({})", c.name).unwrap();
        writeln!(out, "}};").unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "GRAM_NAMESPACE_END").unwrap();
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn layout_pads_like_c() {
        let c = Component { name: "T".into(), fields: vec![
            Field { name: "a".into(), ty: FieldType::Bool },
            Field { name: "b".into(), ty: FieldType::F32 },
        ]};
        assert_eq!(c.layout(), (vec![0, 4], 8));
    }
}
